W_FILTERS = [W1, W2, W3, W4, W5, W6]


def read_mono_16k(path):
    fs, x = wavfile.read(path)
    if fs != FS:
        raise ValueError(f"{path.name}: expected {FS} Hz, got {fs} Hz")

    if x.ndim == 2:
        x = x.mean(axis=1)

    if np.issubdtype(x.dtype, np.integer):
        info = np.iinfo(x.dtype)
        scale = float(max(abs(info.min), info.max))
        x = x.astype(np.float32) / scale
    else:
        x = x.astype(np.float32)

    return x


def causal_fir_batch(x, kernels):
    """
    x:       [B, 1, T]
    kernels: [K, 1, L]
    returns: [B, K, T]

    PyTorch conv1d performs correlation, so FIR taps are flipped.
    Left padding of L-1 gives causal lfilter-equivalent output length T.
    """
    L = kernels.shape[-1]
    xpad = F.pad(x, (L - 1, 0))
    return F.conv1d(xpad, torch.flip(kernels, dims=[-1]))


def main():
    if len(P_hat) == 0 or len(S_hat) == 0 or any(len(w) == 0 for w in W_FILTERS):
        raise RuntimeError("Paste P_hat, S_hat, and W1..W6 coefficients first.")

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    # Precompute control path G_i = S_hat * W_i.
    G = [np.convolve(S_hat, w).astype(np.float32) for w in W_FILTERS]

    p_kernel = torch.tensor(P_hat, dtype=torch.float32, device=device).view(1, 1, -1)
    g_kernels = torch.tensor(np.stack(G), dtype=torch.float32, device=device).view(6, 1, -1)

    wavs = sorted(DATA_DIR.glob("*.wav"))
    if not wavs:
        raise FileNotFoundError(DATA_DIR)

    counts = np.zeros(6, dtype=np.int64)
    rows = []

    for start in tqdm(range(0, len(wavs), BATCH_SIZE), desc="Fast labeling"):
        batch_paths = wavs[start:start+BATCH_SIZE]
        xs = [read_mono_16k(p) for p in batch_paths]

        # This dataset generator creates fixed 1-second length files.
        x_np = np.stack(xs, axis=0)
        x = torch.from_numpy(x_np).to(device).unsqueeze(1)  # [B,1,T]

        with torch.no_grad():
            d = causal_fir_batch(x, p_kernel)        # [B,1,T]
            sy = causal_fir_batch(x, g_kernels)     # [B,6,T]
            e = d - sy

            p_d = torch.sum(d * d, dim=-1)           # [B,1]
            p_e = torch.sum(e * e, dim=-1)           # [B,6]

            nr = 10.0 * torch.log10((p_d + 1e-20) / (p_e + 1e-20))
            best = torch.argmax(nr, dim=1)

        nr_cpu = nr.cpu().numpy()
        best_cpu = best.cpu().numpy()

        for j, path in enumerate(batch_paths):
            idx = int(best_cpu[j])
            counts[idx] += 1

            vals = nr_cpu[j]
            row = {
                "filename": path.name,
                "label": FILTER_NAMES[idx],
                "band": FILTER_BANDS[idx],
                "best_nr_db": float(vals[idx]),
            }
            for k in range(6):
                row[f"nr_W{k+1}_db"] = float(vals[k])

            rows.append(row)

    fields = [
        "filename", "label", "band", "best_nr_db",
        "nr_W1_db", "nr_W2_db", "nr_W3_db",
        "nr_W4_db", "nr_W5_db", "nr_W6_db"
    ]

    with OUT_CSV.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    total = counts.sum()
    print()
    print("=========== Label distribution ===========")
    for i, c in enumerate(counts):
        print(f"{FILTER_NAMES[i]} ({FILTER_BANDS[i]:>9s}) : {c:6d} ({100*c/total:6.2f}%)")
    print("==========================================")
    print(f"Saved: {OUT_CSV}")


if __name__ == "__main__":
    main()
